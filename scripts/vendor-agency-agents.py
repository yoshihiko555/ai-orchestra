def normalize_for_scan(lines: list[str]) -> str:
    """検出用に正規化する（全角→半角・小文字化・行継続の結合・空白の圧縮）。"""
    text = unicodedata.normalize("NFKC", "\n".join(lines)).lower()
    text = re.sub(r"\\\s*\n", " ", text)
    return re.sub(r"\s+", " ", text)


def has_hidden_characters(text: str) -> bool:
    """書式制御文字（ゼロ幅文字など）や双方向テキストの制御文字を含むか。"""
    return any(ch in BIDI_CONTROLS or unicodedata.category(ch) == "Cf" for ch in text)


def parse_frontmatter_or_none(text: str) -> dict | None:
    """frontmatter を解析できれば dict、できなければ None。"""
    try:
        return split_frontmatter(text, "upstream")[0]
    except VendorError:
        return None


def frontmatter_reasons(old_text: str, new_text: str) -> list[str]:
    """frontmatter の変化のうち人が読むべきものを返す。"""
    old_fm = parse_frontmatter_or_none(old_text)
    new_fm = parse_frontmatter_or_none(new_text)
    if old_fm is None and new_fm is None:
        return []
    if old_fm is None or new_fm is None:
        return ["frontmatter を解析できない"]
    reasons = []
    if old_fm.get("description") != new_fm.get("description"):
        reasons.append("description の変更（自動委譲の選ばれ方が変わる）")
    added_keys = sorted(
        set(dropped_frontmatter_keys(new_fm)) - set(dropped_frontmatter_keys(old_fm))
    )
    if added_keys:
        reasons.append(f"frontmatter に未対応のキーが追加（生成物には入らない）: {added_keys}")
    return reasons


def classify_change(spec: AgentSpec, old_text: str, new_text: str) -> AgentChange:
    """1 エージェントの差分を数え、人が読むべき理由を集める。"""
    diff_lines = list(
        difflib.unified_diff(
            old_text.splitlines(),
            new_text.splitlines(),
            fromfile=f"a/{spec.path}.md",
            tofile=f"b/{spec.path}.md",
            lineterm="",
        )
    )
    added = [line[1:] for line in diff_lines if line.startswith("+") and not line.startswith("+++")]
    deleted = [
        line[1:] for line in diff_lines if line.startswith("-") and not line.startswith("---")
    ]
    reasons = [f"tools に {tool}" for tool in spec.tools if tool in REVIEW_TOOLS]
    reasons += frontmatter_reasons(old_text, new_text)
    added_text = normalize_for_scan(added)
    reasons += [f"pattern: {name}" for name, regex in RISK_PATTERNS if regex.search(added_text)]
    raw_added = "\n".join(added)
    if has_hidden_characters(raw_added):
        reasons.append("不可視の制御文字の追加")
    if "<!--" in raw_added:
        reasons.append("HTML コメントの追加（表示されない指示を書ける）")
    if SAFETY_GUARD_RE.search(normalize_for_scan(deleted)):
        reasons.append("安全に関する記述の削除")
    return AgentChange(
        path=spec.path,
        added=len(added),
        deleted=len(deleted),
        reasons=tuple(reasons),
        diff="\n".join(diff_lines),
    )


def collect_new_agents(source: Path, old: str, new: str) -> list[tuple[str, str, str]]:
    """new で増えたエージェントを (パス, 表示名, description) で返す。"""
    added_paths = sorted(
        set(list_upstream_paths(source, new)) - set(list_upstream_paths(source, old))
    )
    found = []
    for path in added_paths:
        summary = read_agent_summary(source, new, path)
        if summary is not None:
            found.append((path, *summary))
    return found


def render_update_report(
    old: str,
    new: str,
    changes: list[AgentChange],
    removed: list[str],
    new_agents: list[tuple[str, str, str]],
) -> str:
    """update の結果を Markdown で組み立てる。要レビューの変更には差分を全文付ける。"""
    review = [c for c in changes if c.needs_review]
    summary_only = [c for c in changes if not c.needs_review]
    lines = [f"## agency-agents update: {old[:7]} → {new[:7]}", ""]
    lines.append(f"### 要レビュー（{len(review)}）")
    for change in review:
        lines.append(
            f"- {change.path} (+{change.added}/-{change.deleted}) — {', '.join(change.reasons)}"
        )
    for change in review:
        lines += ["", f"#### {change.path}", "", "```diff", change.diff, "```"]
    lines += ["", f"### 変更あり・要約のみ（{len(summary_only)}）"]
    lines += [f"- {c.path} (+{c.added}/-{c.deleted})" for c in summary_only]
    lines += ["", f"### upstream で削除（{len(removed)}）"]
    lines += [f"- {path}" for path in removed]
    lines += ["", f"### upstream で追加・取り込み候補（{len(new_agents)}）"]
    lines += [
        f"- {path} ({name}) — {desc[:DESCRIPTION_PREVIEW_CHARS]}" for path, name, desc in new_agents
    ]
    return "\n".join(lines) + "\n"


def replace_commit_line(text: str, new: str) -> str:
    """upstream.yaml の commit 行だけを書き換えた内容を返す（コメントや並びは保つ）。"""
    updated, count = COMMIT_LINE_RE.subn(
        lambda m: f"{m.group(1)}{m.group(2)}{new}{m.group(2)}{m.group(3)}", text
    )
    if count != 1:
        raise VendorError(
            f"{CONFIG_NAME} の commit 行を 1 つに特定できません（`commit: <sha>` の形）"
        )
    return updated


def cmd_update(
    package_dir: Path, source: Path, cli_tools: Path, to_ref: str, dry_run: bool, yes: bool
) -> int:
    """固定する commit を進め、差分を分類して報告する。--yes があれば生成し直す。"""
    config = load_config(package_dir)
    ensure_source_is_upstream(source, config.repo)
    old = config.commit
    new = resolve_commit(source, to_ref)
    if not is_ancestor(source, old, new):
        raise VendorError(
            f"{new[:7]} は現在の {old[:7]} の子孫ではありません（巻き戻しや fork の commit は取り込まない）"
        )
    upstream_paths = set(list_upstream_paths(source, new))

    removed = [spec.path for spec in config.agents if spec.path not in upstream_paths]
    changes = []
    for spec in config.agents:
        if spec.path in removed:
            continue
        old_text = read_upstream(source, old, spec.path)
        new_text = read_upstream(source, new, spec.path)
        if old_text != new_text:
            changes.append(classify_change(spec, old_text, new_text))
    print(render_update_report(old, new, changes, removed, collect_new_agents(source, old, new)))

    if removed:
        print(
            "[error] upstream で削除されたエージェントがあります。upstream.yaml から外してから再実行してください"
        )
        return 1
    if dry_run:
        return 0
    if any(change.needs_review for change in changes) and not yes:
        print("[stop] 要レビューの差分を読んでから、--yes を付けて再実行してください")
        return 1

    # 新しい commit で生成を最後まで試してから書く（失敗しても upstream.yaml を進めない）
    new_config = replace(config, commit=new)
    expected, license_text = build_expected(new_config, source)
    manifest = render_manifest(package_dir, list(expected))
    config_path = package_dir / CONFIG_NAME
    new_config_text = replace_commit_line(config_path.read_text(encoding="utf-8"), new)
    warn_missing_routing([spec.slug for spec in config.agents], cli_tools)
    write_outputs(package_dir, expected, manifest, license_text, {config_path: new_config_text})
    print(f"[update] {len(expected)} agents @ {new[:7]} を生成しました")
    return 0


