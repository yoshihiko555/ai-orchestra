def run_git(source: Path, *args: str, check: bool = True) -> tuple[int, str]:
    """source の clone で git を実行し (終了コード, stdout) を返す。

    clone の .git/config に書かれたフックや fsmonitor でコマンドが走らないように無効化する。
    check=True なら非 0 終了を VendorError にする。
    """
    command = [
        "git",
        "-c",
        "core.fsmonitor=",
        "-c",
        "core.hooksPath=/dev/null",
        "-C",
        str(source),
        *args,
    ]
    try:
        result = subprocess.run(
            command, capture_output=True, timeout=GIT_TIMEOUT_SECONDS, check=False
        )
    except FileNotFoundError as exc:
        raise VendorError("git が見つかりません") from exc
    except subprocess.TimeoutExpired as exc:
        raise VendorError(
            f"git {' '.join(args)} が {GIT_TIMEOUT_SECONDS} 秒で終わりません"
        ) from exc
    if check and result.returncode != 0:
        stderr = result.stderr.decode("utf-8", errors="replace").strip()
        raise VendorError(f"git {' '.join(args)} が失敗しました: {stderr}")
    try:
        return result.returncode, result.stdout.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise VendorError(f"git {' '.join(args)} の出力が UTF-8 ではありません") from exc


def resolve_commit(source: Path, ref: str) -> str:
    """ref を 40 桁の commit SHA に解決する。"""
    # 先頭が - の ref は git のオプションとして解釈されるため拒否する
    if not ref or ref.startswith("-"):
        raise VendorError(f"不正な ref です: {ref!r}")
    _, out = run_git(source, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}")
    sha = out.strip()
    if not SHA_RE.match(sha):
        raise VendorError(f"ref を commit に解決できません: {ref}")
    return sha


def is_ancestor(source: Path, ancestor: str, descendant: str) -> bool:
    """ancestor が descendant の祖先（または同じ commit）なら True。"""
    code, _ = run_git(source, "merge-base", "--is-ancestor", ancestor, descendant, check=False)
    if code not in (0, 1):
        raise VendorError(f"{ancestor[:7]} と {descendant[:7]} の関係を確かめられません")
    return code == 0


def repo_slug(url: str) -> str | None:
    """URL から owner/name を取り出す（大文字小文字は区別しない）。"""
    match = REPO_SLUG_RE.search(url.strip())
    return match.group(1).lower() if match else None


def ensure_source_is_upstream(source: Path, repo: str) -> None:
    """--source の origin が upstream.yaml の repo と同じリポジトリかを確かめる。"""
    _, url = run_git(source, "remote", "get-url", "origin")
    expected = repo_slug(repo)
    if expected is None or repo_slug(url) != expected:
        raise VendorError(
            f"--source の origin（{url.strip()}）が upstream.yaml の repo（{repo}）と一致しません"
        )


def read_upstream_file(source: Path, sha: str, rel: str) -> str:
    """固定した commit からファイルを読む（作業ツリーは見ない）。"""
    try:
        return run_git(source, "show", f"{sha}:{rel}")[1]
    except VendorError as exc:
        raise VendorError(f"upstream の {sha[:7]} の {rel} を読めません: {exc}") from exc


def read_upstream(source: Path, sha: str, path: str) -> str:
    """固定した commit からエージェントの Markdown を読む。"""
    return read_upstream_file(source, sha, f"{path}.md")


def list_upstream_paths(source: Path, sha: str) -> list[str]:
    """commit に含まれる Markdown のパス（拡張子なし）を返す。"""
    _, output = run_git(source, "ls-tree", "-r", "--name-only", sha)
    paths = []
    for name in output.splitlines():
        if not name.endswith(".md"):
            continue
        stem = name[: -len(".md")]
        if AGENT_PATH_RE.match(stem):
            paths.append(stem)
    return sorted(paths)


