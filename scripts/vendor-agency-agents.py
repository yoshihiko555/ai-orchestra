def resolve_tools(path: str, raw: dict) -> tuple[str, ...]:
    """profile / tools からツール一覧を決める。どちらも無ければ既定プロファイル。"""
    if "profile" in raw and "tools" in raw:
        raise VendorError(f"{path}: profile と tools は同時に指定できません")
    if "tools" in raw:
        tools = raw["tools"]
        if not isinstance(tools, list) or not tools:
            raise VendorError(f"{path}: tools は 1 つ以上のツール名のリストにしてください")
        if not all(isinstance(t, str) and t.strip() for t in tools):
            raise VendorError(f"{path}: tools に空や文字列以外の値があります")
        return tuple(t.strip() for t in tools)
    profile = raw.get("profile", DEFAULT_PROFILE)
    if profile not in PROFILES:
        known = ", ".join(PROFILES)
        raise VendorError(f"{path}: 未知の profile です: {profile!r}（使えるもの: {known}）")
    return PROFILES[profile]


def parse_agent_spec(path: object, raw: object) -> AgentSpec:
    """agents の 1 項目を検証して AgentSpec にする。"""
    if not isinstance(path, str) or not AGENT_PATH_RE.match(path):
        raise VendorError(f"不正なエージェントのパスです: {path!r}（例: specialized/foo）")
    if raw is None:
        raw = {}
    if not isinstance(raw, dict):
        raise VendorError(f"{path}: 設定は mapping にしてください")
    unknown = set(raw) - SPEC_KEYS
    if unknown:
        raise VendorError(f"{path}: 未知のキーがあります: {sorted(unknown)}")
    frontmatter = raw.get("frontmatter") or {}
    if not isinstance(frontmatter, dict):
        raise VendorError(f"{path}: frontmatter は mapping にしてください")
    not_allowed = sorted(str(k) for k in frontmatter if k not in OVERRIDABLE_FRONTMATTER_KEYS)
    if not_allowed:
        allowed = ", ".join(sorted(OVERRIDABLE_FRONTMATTER_KEYS))
        raise VendorError(
            f"{path}: frontmatter で上書きできないキーです: {not_allowed}（使えるもの: {allowed}）"
        )
    return AgentSpec(path=path, tools=resolve_tools(path, raw), frontmatter=dict(frontmatter))


def load_config(package_dir: Path) -> VendorConfig:
    """upstream.yaml を読んで検証する。"""
    config_path = package_dir / CONFIG_NAME
    try:
        data = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError) as exc:
        raise VendorError(f"{config_path} を読めません: {exc}") from exc
    except yaml.YAMLError as exc:
        raise VendorError(f"{config_path} の YAML が不正です: {exc}") from exc
    if not isinstance(data, dict):
        raise VendorError(f"{config_path} は mapping にしてください")

    repo = data.get("repo")
    if not isinstance(repo, str) or repo_slug(repo) is None:
        raise VendorError("repo に upstream の URL を書いてください")
    commit = data.get("commit")
    if not isinstance(commit, str) or not SHA_RE.match(commit):
        raise VendorError("commit は 40 桁の小文字 16 進 SHA で固定してください")
    agents_raw = data.get("agents") or {}
    if not isinstance(agents_raw, dict):
        raise VendorError("agents は mapping（パス: 設定）にしてください")

    specs = tuple(parse_agent_spec(path, raw) for path, raw in agents_raw.items())
    # 大文字小文字だけが違う slug も、大文字小文字を区別しないファイルシステムでは衝突する
    slugs = [spec.slug.lower() for spec in specs]
    duplicated = sorted({slug for slug in slugs if slugs.count(slug) > 1})
    if duplicated:
        raise VendorError(f"ファイル名（slug）が重複しています: {duplicated}")
    return VendorConfig(repo=repo, commit=commit, agents=specs)


