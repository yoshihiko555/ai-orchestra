#!/usr/bin/env python3
"""agency-agents（upstream）のエージェントを commit 固定で取り込み、packages/agency-agents を生成する。

正本は packages/agency-agents/upstream.yaml。agents/*.md・manifest.json の agents・LICENSE-agency-agents は
生成物で、手で編集しない。upstream はローカルの clone（--source）から `git show <sha>:<path>` で読むため、
clone の作業ツリーやチェックアウト中のブランチには依存しない。外部への送信は行わない。

upstream の frontmatter は description と表示用のキーだけを通す（hooks / mcpServers / permissionMode 等を
upstream が足しても生成物には入れない）。ツール権限は upstream.yaml の profile / tools だけで決まる。

使い方:
    vendor-agency-agents.py sync   --source <clone> [--check]
    vendor-agency-agents.py update --source <clone> --to <ref> [--dry-run] [--yes]
    vendor-agency-agents.py list   --source <clone> [--ref <ref>] [--query <text>]
"""

