def split_frontmatter(text: str, path: str) -> tuple[dict, str]:
    """Markdown を frontmatter（dict）と本文に分ける。"""
    match = FRONTMATTER_RE.match(text)
    if match is None:
        raise VendorError(f"{path}.md に frontmatter がありません")
    try:
        frontmatter = yaml.safe_load(match.group(1))
    except yaml.YAMLError as exc:
        raise VendorError(f"{path}.md の frontmatter が不正です: {exc}") from exc
    if not isinstance(frontmatter, dict):
        raise VendorError(f"{path}.md の frontmatter が mapping ではありません")
    description = frontmatter.get("description")
    if not isinstance(description, str) or not description.strip():
        raise VendorError(f"{path}.md の frontmatter に文字列の description がありません")
    return frontmatter, match.group(2)


def dropped_frontmatter_keys(frontmatter: dict) -> list[str]:
    """生成物に通さない upstream の frontmatter キー（name / tools は上書きするので除く）。"""
    passed = set(UPSTREAM_FRONTMATTER_KEYS) | {"name", "tools"}
    return sorted(str(key) for key in frontmatter if key not in passed)


def read_license(text: str) -> tuple[str, str]:
    """LICENSE からライセンス名（先頭行）と著作権表示の行を取り出す。"""
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    copyright_line = next((line for line in lines if line.lower().startswith("copyright")), None)
    if not lines or copyright_line is None:
        raise VendorError("upstream の LICENSE にライセンス名か著作権表示がありません")
    return lines[0], copyright_line


def render_agent(
    spec: AgentSpec, upstream_text: str, config: VendorConfig, license_text: str
) -> str:
    """upstream の Markdown に frontmatter の上書きを当てて生成物にする。本文は変えない。"""
    upstream_fm, body = split_frontmatter(upstream_text, spec.path)
    rendered: dict = {
        "name": spec.slug,
        "description": upstream_fm["description"],
        "tools": ", ".join(spec.tools),
    }
    for key in UPSTREAM_FRONTMATTER_KEYS:
        if key in upstream_fm and key not in rendered:
            rendered[key] = upstream_fm[key]
    rendered.update(spec.frontmatter)
    dumped = yaml.dump(
        rendered,
        Dumper=_NoAliasDumper,
        sort_keys=False,
        allow_unicode=True,
        width=1_000_000,
        default_flow_style=False,
    )
    license_name, copyright_line = read_license(license_text)
    marker = GENERATED_MARKER.format(
        repo=repo_slug(config.repo),
        sha=config.commit[:7],
        path=spec.path,
        license=license_name,
        copyright=copyright_line,
    )
    return f"---\n{dumped}---\n{marker}\n{body}"


def build_expected(config: VendorConfig, source: Path) -> tuple[dict[str, str], str]:
    """生成すべき agents/*.md（{ファイル名: 内容}）と LICENSE の内容を返す。"""
    resolved = resolve_commit(source, config.commit)
    if resolved != config.commit:
        raise VendorError(f"source に commit {config.commit} がありません")
    license_text = read_upstream_file(source, config.commit, UPSTREAM_LICENSE_PATH)
    agents = {}
    for spec in config.agents:
        upstream_text = read_upstream(source, config.commit, spec.path)
        dropped = dropped_frontmatter_keys(split_frontmatter(upstream_text, spec.path)[0])
        if dropped:
            print(
                f"[warn] {spec.path}: upstream の frontmatter のキー {dropped} は生成物に入れません",
                file=sys.stderr,
            )
        agents[f"{spec.slug}.md"] = render_agent(spec, upstream_text, config, license_text)
    return agents, license_text


def render_manifest(package_dir: Path, filenames: list[str]) -> str:
    """既存の manifest.json の agents だけを差し替えた内容を返す。"""
    manifest_path = package_dir / MANIFEST_NAME
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise VendorError(f"{manifest_path} を読めません: {exc}") from exc
    manifest["agents"] = [f"{AGENTS_DIRNAME}/{name}" for name in sorted(filenames)]
    return format_manifest(manifest)


def format_manifest(manifest: dict) -> str:
    """prettier（printWidth 80）と同じ形で書く。hook が整形しても --check がずれないようにするため。"""
    items = list(manifest.items())
    lines = ["{"]
    for index, (key, value) in enumerate(items):
        comma = "," if index < len(items) - 1 else ""
        head = f"  {json.dumps(key, ensure_ascii=False)}: "
        inline = json.dumps(value, ensure_ascii=False, separators=(", ", ": "))
        if not isinstance(value, list) or len(head + inline + comma) <= PRETTIER_PRINT_WIDTH:
            lines.append(head + inline + comma)
            continue
        lines.append(head + "[")
        for item_index, item in enumerate(value):
            item_comma = "," if item_index < len(value) - 1 else ""
            lines.append(f"    {json.dumps(item, ensure_ascii=False)}{item_comma}")
        lines.append(f"  ]{comma}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def warn_missing_routing(slugs: list[str], cli_tools: Path) -> list[str]:
    """cli-tools.yaml の agents に無いエージェントを警告する（エラーにはしない）。"""
    try:
        data = yaml.safe_load(cli_tools.read_text(encoding="utf-8")) or {}
    except (OSError, UnicodeDecodeError, yaml.YAMLError):
        print(f"[warn] {cli_tools} を読めないためルーティング設定を照合できません", file=sys.stderr)
        return list(slugs)
    agents = data.get("agents") if isinstance(data, dict) else None
    routed = set(agents) if isinstance(agents, dict) else set()
    missing = [slug for slug in slugs if slug not in routed]
    for slug in missing:
        print(
            f"[warn] cli-tools.yaml の agents に {slug} がありません（ルーティングは既定値になります）",
            file=sys.stderr,
        )
    return missing


def is_generated(path: Path) -> bool:
    """このスクリプトが生成したファイル（印のコメントを持つ）か。読めなければ False。"""
    try:
        return GENERATED_MARKER_PREFIX in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def same_content(path: Path, content: str) -> bool:
    """ファイルが content と同じか。読めない・壊れたリンクは「違う」とみなす。"""
    try:
        return path.read_bytes() == content.encode("utf-8")
    except OSError:
        return False


def find_differences(
    package_dir: Path, expected: dict[str, str], manifest: str, license_text: str
) -> list[str]:
    """生成物とディスク上のファイルの食い違いを列挙する。"""
    agents_dir = package_dir / AGENTS_DIRNAME
    actual = {p.name: p for p in agents_dir.iterdir()} if agents_dir.is_dir() else {}
    problems = []
    for name in sorted(set(expected) - set(actual)):
        problems.append(f"生成されていません: {AGENTS_DIRNAME}/{name}")
    for name in sorted(set(actual) - set(expected)):
        problems.append(f"upstream.yaml に無いファイルがあります: {AGENTS_DIRNAME}/{name}")
    for name in sorted(set(expected) & set(actual)):
        if not same_content(actual[name], expected[name]):
            problems.append(
                f"生成物と一致しません（手で編集された可能性）: {AGENTS_DIRNAME}/{name}"
            )
    if not same_content(package_dir / MANIFEST_NAME, manifest):
        problems.append(f"{MANIFEST_NAME} の agents が upstream.yaml と一致しません")
    if not same_content(package_dir / LICENSE_NAME, license_text):
        problems.append(f"{LICENSE_NAME} が upstream の LICENSE と一致しません")
    return problems


def write_files_atomically(files: dict[Path, str]) -> None:
    """全ファイルを一時ファイルに書き終えてから置き換える（途中で失敗しても半端に残さない）。"""
    staged: list[tuple[str, Path]] = []
    try:
        for target, content in files.items():
            target.parent.mkdir(parents=True, exist_ok=True)
            fd, tmp = tempfile.mkstemp(dir=target.parent, prefix=f".{target.name}.", suffix=".tmp")
            with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
                handle.write(content)
            staged.append((tmp, target))
        for tmp, target in staged:
            os.replace(tmp, target)
    except OSError as exc:
        for tmp, _ in staged:
            Path(tmp).unlink(missing_ok=True)
        raise VendorError(f"書き込みに失敗しました: {exc}") from exc


def write_outputs(
    package_dir: Path,
    expected: dict[str, str],
    manifest: str,
    license_text: str,
    extra: dict[Path, str] | None = None,
) -> None:
    """生成物（と extra）をまとめて書き、upstream.yaml から外れた生成物を消す。

    手で置いたファイル（生成物の印が無いもの）と symlink は消さない。
    """
    agents_dir = package_dir / AGENTS_DIRNAME
    files = {agents_dir / name: content for name, content in expected.items()}
    files[package_dir / MANIFEST_NAME] = manifest
    files[package_dir / LICENSE_NAME] = license_text
    files.update(extra or {})
    write_files_atomically(files)
    for stale in agents_dir.glob("*.md"):
        if stale.name in expected:
            continue
        if stale.is_symlink() or not is_generated(stale):
            print(
                f"[warn] 生成物ではないため残しました: {AGENTS_DIRNAME}/{stale.name}",
                file=sys.stderr,
            )
            continue
        stale.unlink()


def cmd_sync(package_dir: Path, source: Path, cli_tools: Path, check: bool) -> int:
    """upstream.yaml に従って生成する。check なら書かずに食い違いだけを報告する。"""
    config = load_config(package_dir)
    expected, license_text = build_expected(config, source)
    manifest = render_manifest(package_dir, list(expected))
    warn_missing_routing([spec.slug for spec in config.agents], cli_tools)
    if check:
        problems = find_differences(package_dir, expected, manifest, license_text)
        for problem in problems:
            print(f"[check] {problem}")
        if problems:
            print("`sync` を実行して生成し直してください")
            return 1
        print(f"[check] OK: {len(expected)} agents @ {config.commit[:7]}")
        return 0
    write_outputs(package_dir, expected, manifest, license_text)
    print(f"[sync] {len(expected)} agents @ {config.commit[:7]} を生成しました")
    return 0


