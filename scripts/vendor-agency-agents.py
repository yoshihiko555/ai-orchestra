def read_agent_summary(source: Path, sha: str, path: str) -> tuple[str, str] | None:
    """エージェントなら (表示名, description) を返す。frontmatter の無い文書は None。"""
    try:
        frontmatter, _ = split_frontmatter(read_upstream(source, sha, path), path)
    except VendorError:
        return None
    return str(frontmatter.get("name", path)), " ".join(frontmatter["description"].split())


def cmd_list(package_dir: Path, source: Path, ref: str | None, query: str | None) -> int:
    """upstream のエージェントを description 付きで表示し、取り込み済みに印を付ける。"""
    config = load_config(package_dir)
    sha = resolve_commit(source, ref) if ref else config.commit
    imported = {spec.path for spec in config.agents}
    needle = (query or "").lower()
    shown = 0
    for path in list_upstream_paths(source, sha):
        summary = read_agent_summary(source, sha, path)
        if summary is None:
            continue
        name, description = summary
        if needle and needle not in f"{path}\n{name}\n{description}".lower():
            continue
        mark = "[x]" if path in imported else "[ ]"
        preview = description[:DESCRIPTION_PREVIEW_CHARS]
        if len(description) > DESCRIPTION_PREVIEW_CHARS:
            preview += "…"
        print(f"{mark} {path}  ({name}) — {preview}")
        shown += 1
    print(f"\n{shown} agents @ {sha[:7]}（[x] = 取り込み済み）")
    return 0


