def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--package-dir", type=Path, default=DEFAULT_PACKAGE_DIR)
    parser.add_argument("--cli-tools", type=Path, default=DEFAULT_CLI_TOOLS)
    sub = parser.add_subparsers(dest="command", required=True)

    sync = sub.add_parser("sync", help="upstream.yaml に従って生成する")
    sync.add_argument("--source", type=Path, required=True, help="upstream のローカル clone")
    sync.add_argument("--check", action="store_true", help="書かずに食い違いを検出する")

    update = sub.add_parser("update", help="固定する commit を進めて差分を報告する")
    update.add_argument("--source", type=Path, required=True, help="upstream のローカル clone")
    update.add_argument("--to", required=True, help="進め先の ref（SHA・ブランチ・タグ）")
    update.add_argument("--dry-run", action="store_true", help="報告だけして書き換えない")
    update.add_argument(
        "--yes", action="store_true", help="要レビューの差分を読んだうえで書き換える"
    )

    listing = sub.add_parser("list", help="upstream のエージェントを一覧する")
    listing.add_argument("--source", type=Path, required=True, help="upstream のローカル clone")
    listing.add_argument("--ref", help="一覧する ref（既定: upstream.yaml の commit）")
    listing.add_argument("--query", help="パス・名前・description の部分一致で絞る")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    package_dir = args.package_dir.expanduser().resolve()
    source = args.source.expanduser().resolve()
    cli_tools = args.cli_tools.expanduser()
    try:
        if args.command == "sync":
            return cmd_sync(package_dir, source, cli_tools, args.check)
        if args.command == "update":
            return cmd_update(package_dir, source, cli_tools, args.to, args.dry_run, args.yes)
        return cmd_list(package_dir, source, args.ref, args.query)
    except VendorError as exc:
        print(f"[error] {exc}", file=sys.stderr)
        return EXIT_ERROR


if __name__ == "__main__":
    sys.exit(main())
