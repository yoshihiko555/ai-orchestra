def _project_slug(project_dir: str) -> str:
    """Return a short stable hash of project_dir, for a per-project-unique launchd label
    (#H16): multiple projects sharing the same `loop_scheduler.py` script path (e.g. installed
    from the same ai-orchestra package into different repos) must not collide on one fixed
    label - launchd treats the label as a unique job identifier, so a second project's
    `launchctl load` would either silently no-op or clobber the first project's job.
    """
    material = str(Path(project_dir).resolve())
    return hashlib.sha256(material.encode("utf-8")).hexdigest()[:12]


# RM3: any C0 control character other than TAB (#x9) and LF (#xA) - this deliberately also
# matches CR (#xD, 0x0D falls in the 0x0B-0x1F span below), see `_reject_launchd_unsafe_chars`.
_LAUNCHD_UNSAFE_CHARS_RE = re.compile(r"[\x00-\x08\x0b-\x1f]")


def _reject_launchd_unsafe_chars(value: str, field_name: str) -> None:
    """Fail closed (RM3) when a launchd-interpolated value contains CR or another control
    character XML 1.0 does not treat as plain, unchanged text.

    `render_launchd_plist` XML-escapes `&`/`<`/`>` (#12), but that alone does not cover control
    characters. A literal CR (`\\r`) is not illegal XML content, but XML 1.0 mandates line-ending
    normalization at parse time (CR, CRLF, and a lone CR are all folded to a single LF) - so a
    `project_dir`/script/interpreter/`--definition` value containing a literal CR would silently
    resolve to a *different* string the moment any XML parser (including launchd's own plist
    reader) reads this file back, with no error to signal the mismatch between what was
    rendered here and what launchd actually invokes. Any other C0 control character outside the
    small XML-1.0-legal set (TAB `#x9`, LF `#xA`, CR `#xD`) is not merely re-normalized but
    outright illegal XML 1.0 content, producing a plist no XML parser can parse at all.

    Neither failure mode has a character-level escape available at the plist-XML level (unlike
    `&`/`<`/`>`, which `xml_escape` already handles) - refusing to render is the only safe
    outcome here, mirroring `_reject_cron_unsafe_chars`'s CR/LF fail-closed precedent for
    `render_cron_entry`. A lone LF is intentionally *not* rejected here (unlike the cron guard,
    which fails closed on LF too): LF is XML-1.0-legal and passes through XML parsing completely
    unchanged - no normalization applies to it - so it carries neither of the two failure modes
    above.
    """
    if _LAUNCHD_UNSAFE_CHARS_RE.search(value):
        raise ValueError(
            f"{field_name} must not contain CR or other control characters for a launchd "
            f"plist: {value!r}"
        )


def render_launchd_plist(
    project_dir: str,
    script_path: Path | None = None,
    python_bin: str | None = None,
    definition_id: str = DEFAULT_DEFINITION_ID,
) -> str:
    """Render a launchd plist template for `--install-launchd`-style manual setup.

    Every interpolated path is XML-escaped (#12): an unescaped `&`/`<`/`>` in `project_dir`
    would otherwise produce invalid plist XML.

    Uses `sys.executable` rather than a hardcoded `/usr/bin/python3` (#G8): a launchd job
    started with the system interpreter cannot import a venv/uv-managed dependency the
    scheduler itself was actually installed under, so the resident job would die immediately
    on start. Mirrors the same fix already applied to `spawn_worker` (#F10).

    `--definition` is only appended when it differs from `DEFAULT_DEFINITION_ID` (#H15):
    without it, `--install-launchd`-generated jobs for a non-default loop definition would
    silently poll the wrong (default) definition's label/interval forever.

    The `Label` is suffixed with a hash of `project_dir` (#H16, see `_project_slug`) so
    multiple projects never collide on one fixed launchd job identifier.

    J6: the `Label` is additionally suffixed with `definition_id` whenever it differs from
    `DEFAULT_DEFINITION_ID`, mirroring J4's cron-guard fix. `launchd.plist(5)` requires `Label`
    to uniquely identify the job to launchd; without this, generating plists for both the
    default loop and a non-default `--definition` in the same project would produce two plists
    with identical labels (only `ProgramArguments` differs), and loading the second collides
    with the first - one definition's label queue silently never gets scheduled. The raw
    `definition_id` (not a hash/slug) is used as the suffix, same as it already appears
    verbatim in `--definition` within `ProgramArguments` below - it needs no extra
    sanitization beyond what this function already applies to it (the `_reject_launchd_unsafe_
    chars` control-character check above, plus `xml_escape` on the assembled `label` itself).

    The `ProgramArguments` command is wrapped in `/bin/sh -c 'mkdir -p ... && exec ...'` (#H17):
    `.claude/loop/` may not exist yet on a fresh checkout, and launchd's `StandardOutPath` /
    `StandardErrorPath` redirection fails outright (job never starts) if its parent directory
    is missing - unlike a shell's `>>` redirection, launchd does not create it. `exec` replaces
    the shell so the scheduler still becomes the tracked/`KeepAlive`-monitored process,
    matching a plain direct invocation for restart purposes.

    SN4: the in-template `mkdir -p` above is unlikely to actually help on its own - launchd
    opens `StandardOutPath`/`StandardErrorPath` for redirection *before* `ProgramArguments` is
    exec'd, so by the time `mkdir -p` in this wrapper shell runs, launchd may have already
    failed to open those paths. The log dir is therefore also (redundantly, but authoritatively)
    created eagerly by `main()`'s `print-launchd` handler at template-generation time - i.e. the
    log dir is expected to already exist by the time this plist is ever installed/loaded. The
    in-template `mkdir -p` is left in place as a harmless belt-and-suspenders guard (e.g. if the
    log dir is deleted after generation but before install).

    RM3: every interpolated value (`script`/`project`/`python`/`definition_id`) is also
    rejected outright (`ValueError`) if it contains a literal CR or any other XML-1.0-illegal
    control character - see `_reject_launchd_unsafe_chars` for why `xml_escape` alone (which
    only covers `&`/`<`/`>`) does not protect against those. This mirrors
    `render_cron_entry`'s SN-cron CR/LF fail-closed guard, applied to launchd's XML format
    instead of crontab's line-oriented one.
    """
    script = str(script_path or _SCRIPT_DIR / "loop_scheduler.py")
    project = str(Path(project_dir).resolve())
    python = str(python_bin or sys.executable)
    for value, field_name in (
        (script, "script_path"),
        (project, "project_dir"),
        (python, "python_bin"),
        (definition_id, "definition_id"),
    ):
        _reject_launchd_unsafe_chars(value, field_name)
    log_dir = f"{project}/.claude/loop"
    stdout_log = f"{log_dir}/scheduler.stdout.log"
    stderr_log = f"{log_dir}/scheduler.stderr.log"
    label = f"com.ai-orchestra.loop-scheduler.{_project_slug(project)}"
    definition_args = ""
    if definition_id != DEFAULT_DEFINITION_ID:
        definition_args = f" --definition {shlex.quote(definition_id)}"
        # J6: keep the label unique per non-default definition too - see docstring above.
        label += f".{definition_id}"
    exec_command = (
        f"mkdir -p {shlex.quote(log_dir)} && exec {shlex.quote(python)} {shlex.quote(script)} "
        f"--project {shlex.quote(project)}{definition_args}"
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
        '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
        '<plist version="1.0">\n'
        "<dict>\n"
        "  <key>Label</key>\n"
        f"  <string>{xml_escape(label)}</string>\n"
        "  <key>ProgramArguments</key>\n"
        "  <array>\n"
        "    <string>/bin/sh</string>\n"
        "    <string>-c</string>\n"
        f"    <string>{xml_escape(exec_command)}</string>\n"
        "  </array>\n"
        "  <key>RunAtLoad</key>\n"
        "  <true/>\n"
        "  <key>KeepAlive</key>\n"
        "  <true/>\n"
        "  <key>StandardOutPath</key>\n"
        f"  <string>{xml_escape(stdout_log)}</string>\n"
        "  <key>StandardErrorPath</key>\n"
        f"  <string>{xml_escape(stderr_log)}</string>\n"
        "</dict>\n"
        "</plist>\n"
    )


def _reject_cron_unsafe_chars(value: str, field_name: str) -> None:
    """Fail closed (SN-cron) when a cron-interpolated value contains a literal CR/LF.

    See `render_cron_entry`'s SN-cron docstring note for why this cannot be escaped away the
    way `%` is (SN7) and must instead refuse to render at all.
    """
    if "\n" in value or "\r" in value:
        raise ValueError(f"{field_name} must not contain CR/LF for a cron entry: {value!r}")


def render_cron_entry(
    project_dir: str,
    script_path: Path | None = None,
    python_bin: str | None = None,
    definition_id: str = DEFAULT_DEFINITION_ID,
) -> str:
    """Render a cron entry template: `pgrep` guard that restarts the scheduler if it died.

    Every interpolated path is shell-quoted individually (#12): an unescaped `project_dir`
    containing whitespace or shell metacharacters (`;`, `|`, `&`, ...) would otherwise split
    into extra tokens or inject additional commands into the crontab line.

    Uses `sys.executable` rather than a hardcoded `/usr/bin/python3` (#G8), matching the same
    fix in `render_launchd_plist` and `spawn_worker` (#F10): cron's own minimal environment
    would otherwise invoke a system interpreter that cannot import a venv/uv-managed
    dependency the scheduler was actually installed under.

    `--definition` is only appended when it differs from `DEFAULT_DEFINITION_ID` (#H15),
    mirroring `render_launchd_plist`: otherwise a cron-restarted scheduler for a non-default
    loop definition would silently fall back to polling the default definition's label.

    `pgrep -f` matches against the *entire* pattern string given, so the guard now matches on
    `<script> --project <project>` (not the script path alone) (#H16): with multiple projects
    installed from the same `loop_scheduler.py` script, a script-path-only pattern would treat
    any other project's already-running scheduler as "this project's scheduler is alive" and
    skip starting a new one for the current project entirely.

    J4: when `definition_id` differs from `DEFAULT_DEFINITION_ID`, the pgrep pattern also
    includes `--definition <definition_id>` (mirroring the `definition_args` already appended
    to the fallback command). Without this, a project running multiple concurrent schedulers
    for different non-default definitions (or one non-default definition alongside the
    default) would have every non-default cron entry's liveness guard match on *any* already-
    running scheduler for that project - including one for a completely different definition -
    and skip starting the requested definition's own scheduler, leaving its label queue never
    processed.

    `script`/`project` are `re.escape`-d before being embedded in the `pgrep -f` pattern
    (SM2): `pgrep -f` interprets its argument as a POSIX extended regular expression, not a
    literal string, so an unescaped path containing ERE metacharacters (`( ) + [ ] * ? |`
    etc. - all legal filesystem-path characters) could fail to match at all or match the
    wrong process. This is unrelated to the `shlex.quote` calls elsewhere in this function,
    which only protect *shell* parsing of the crontab line, not `pgrep`'s own regex parsing
    of the (already shell-unescaped) pattern string it receives. `render_launchd_plist` has
    no equivalent issue: its `ProgramArguments` array passes the script path as a literal
    argv element (no shell/regex re-parsing), so no such escaping is needed there.

    The cron line is prefixed with `mkdir -p <log dir> &&` (#H17): `.claude/loop/` may not
    exist yet on a fresh checkout, and the shell's `>> ... 2>&1` redirection at the end of this
    line fails outright (whole command errors out, scheduler never starts) if its parent
    directory is missing.

    #13 / Issue #219 P2-3: `pgrep -f <pattern>` also matches the cron wrapper shell's own argv,
    since the *entire* crontab command line (including this pgrep invocation's own text) is
    visible to `pgrep -f` and literally contains the pattern text a second time in the fallback
    `python3 <script> --project <project>` invocation. Left unaddressed, this self-match makes
    `pgrep -f <pattern>` succeed on *every* cron tick regardless of whether the real scheduler
    is actually alive -- a dead scheduler is then never restarted, since `||`'s fallback never
    runs. A textual pattern tweak (e.g. the classic `[l]oop_scheduler.py` bracket trick) cannot
    fix this because the self-match comes from the fallback command's own text, not from the
    pgrep invocation's own argv.

    Fixed by piping `pgrep -f <pattern>`'s output through `grep -vxF -e "$$" -e "$PPID"` before
    checking whether anything remains (`| grep -q .`): `$$` is this cron-invoked shell's own
    PID (the wrapper whose argv contains the fallback text and therefore self-matches) and
    `$PPID` its parent, both portable POSIX/bash/dash shell built-ins evaluated fresh on every
    tick (no Python `os.getpid()` call is possible here -- there is no live Python process
    inside this shell one-liner until the fallback itself runs). `-x`/`-F` match each pgrep
    output line (a bare PID) as a whole literal string, avoiding a partial-substring collision
    between different PIDs. This closes the concrete "dead scheduler treated as alive forever"
    failure mode without changing the pipeline's overall `... || <fallback>` exit-status
    contract: if pgrep finds nothing beyond this shell's own PID/parent, the filtered pipeline's
    final `grep -q .` exits non-zero and the fallback still runs; if a genuinely different,
    still-alive scheduler process also matches, at least one non-excluded PID survives the
    filter and the fallback is skipped, exactly as before.

    Known residual limitation (accepted as-is, per Codex review of this exact fix): only this
    shell's own PID and its immediate parent are excluded, not the full ancestor chain -- an
    unrelated process that independently happens to contain the pattern text, or PIDs from a
    concurrently-running second cron guard invocation, could still cause a false "alive" match.
    A fully race-free liveness check needs a pidfile/flock written by `loop_scheduler.py`
    itself at startup, which remains a larger, riskier redesign than belongs in a
    template-rendering fix; left as a follow-up rather than bundled here.

    Every literal `%` in the assembled line is escaped to `\\%` (SN7): `crontab` treats an
    unescaped `%` as a newline at the crontab-file-parsing stage, *before* the shell ever
    sees the line - splitting the command there (and feeding the remainder to the command's
    stdin) regardless of any `shlex.quote` shell-quoting already applied. A `project_dir`
    containing a literal `%` (a legal filesystem-path character) would otherwise silently
    truncate this cron entry into a broken, partially-executed command.

    SN-cron: a literal CR/LF in any interpolated value fails closed (`ValueError`) instead of
    being rendered. `shlex.quote` only protects *shell* word-splitting/metacharacters within
    the assembled line, and (unlike `%`, fixed above by SN7's escape) an embedded CR/LF cannot
    be escaped away at the crontab-file level either - crontab treats a raw newline in a field
    value as its own line terminator at the file-parsing stage, splitting one intended cron
    entry into two (a malformed second "command"), regardless of any quoting applied to the
    line's text. Since there is no crontab-level escape for this (unlike `%`), refusing to
    render is the only safe outcome for a `project_dir`/script/interpreter path containing one
    (CR/LF is technically legal in a POSIX filename, if vanishingly rare in practice).
    """
    script = str(script_path or _SCRIPT_DIR / "loop_scheduler.py")
    project = str(Path(project_dir).resolve())
    python = str(python_bin or sys.executable)
    for value, field_name in (
        (script, "script_path"),
        (project, "project_dir"),
        (python, "python_bin"),
        (definition_id, "definition_id"),
    ):
        _reject_cron_unsafe_chars(value, field_name)
    log_dir = f"{project}/.claude/loop"
    log_path = f"{log_dir}/scheduler.log"
    definition_args = ""
    if definition_id != DEFAULT_DEFINITION_ID:
        definition_args = f" --definition {shlex.quote(definition_id)}"
    # `pgrep -f <pattern>` treats <pattern> as a POSIX extended regular expression, not a
    # literal string (SM2): an unescaped `script`/`project` containing ERE metacharacters
    # (`( ) + [ ] * ? |` etc., all legal in a filesystem path) would either fail to match at
    # all (e.g. an unbalanced `(`) or match something other than the literal path intended.
    # `re.escape` backslash-escapes those metacharacters so pgrep matches them literally.
    pgrep_pattern = f"{re.escape(script)} --project {re.escape(project)}"
    # J4: include the definition id in the liveness pattern whenever it is part of the actual
    # command (i.e. non-default), so this guard cannot mistake a running scheduler for a
    # *different* definition as proof this definition's own scheduler is already alive.
    if definition_id != DEFAULT_DEFINITION_ID:
        pgrep_pattern += f" --definition {re.escape(definition_id)}"
    # `grep -vxF -e "$$" -e "$PPID"` drops the pgrep self-match: the cron wrapper shell's own
    # `pgrep -f` argv contains the fallback launch command, so without this the guard would see
    # itself and conclude a scheduler is already alive. Residual (best-effort) limitations,
    # accepted here because layer-2 lease fencing is the real single-writer guarantee: only the
    # wrapper's own pid (`$$`) and immediate parent (`$PPID`) are excluded, not the full ancestor
    # chain, and concurrent cron firings are not coordinated with each other. A pidfile/flock
    # redesign is the complete fix and is tracked as a separate follow-up.
    line = (
        f"*/5 * * * * mkdir -p {shlex.quote(log_dir)} && "
        f'pgrep -f {shlex.quote(pgrep_pattern)} | grep -vxF -e "$$" -e "$PPID" | grep -q . || '
        f"{shlex.quote(python)} {shlex.quote(script)} --project {shlex.quote(project)}"
        f"{definition_args} >> {shlex.quote(log_path)} 2>&1\n"
    )
    return line.replace("%", "\\%")


