@dataclass
class SchedulerRuntime:
    """In-process worker bookkeeping across poll cycles (not persisted to disk)."""

    workers: dict[str, subprocess.Popen[bytes]] = field(default_factory=dict)
    stopped_loop_ids: set[str] = field(default_factory=set)
    # code H4: loop_id -> monotonic deadline before which a foreign-lease-rejected worker must
    # not be respawned (anti restart-storm guard; in-memory/per-scheduler-process only).
    foreign_lease_cooldown_until: dict[str, float] = field(default_factory=dict)


def _respawn_expired_cooldowns(runtime: SchedulerRuntime, project_dir: str) -> list[str]:
    """Respawn any `loop_id` whose foreign-lease cooldown has elapsed (code H4).

    Respects the concurrency cap (#11): if all worker slots are occupied, a still-expired
    cooldown is left in `foreign_lease_cooldown_until` (so it stays excluded from fresh
    discovery via `spawn_new_workers`) and is retried on a later cycle once a slot frees up
    (SN1: via `_available_worker_slots`, shared with `spawn_new_workers` and
    `respawn_orphaned_active_loops`).

    The (git-resolution-requiring) `_available_worker_slots` call is skipped entirely when
    there is nothing expired to respawn - this function runs every poll cycle regardless of
    whether any foreign-lease cooldown is even pending, so paying for an occupancy
    calculation nobody needs on the common empty-cooldown cycle would be wasted work.

    J1: `_recheck_repo_identity_before_respawn` re-verifies repo-identity immediately before
    respawning any expired-cooldown loop_id here, for the same reason it guards
    `respawn_orphaned_active_loops` and `reap_finished_workers`'s crash-restart branch - see
    that helper's docstring.
    """
    now = time.monotonic()
    expired = [
        loop_id
        for loop_id, deadline in runtime.foreign_lease_cooldown_until.items()
        if now >= deadline
    ]
    if not expired:
        return []
    available = _available_worker_slots(runtime, project_dir)
    respawned: list[str] = []
    expected_repo_identity_hash: str | None = None
    for loop_id in expired:
        if loop_id in runtime.workers or loop_id in runtime.stopped_loop_ids:
            del runtime.foreign_lease_cooldown_until[loop_id]
            continue
        state = _try_load_state(lc.loop_dir(loop_id, project_dir), project_dir)
        if state is None or not should_restart(state.status):
            del runtime.foreign_lease_cooldown_until[loop_id]
            continue
        if available <= 0:
            continue
        if expected_repo_identity_hash is None:
            expected_repo_identity_hash = wm.resolve_repo_identity_hash(project_dir)
        if not _recheck_repo_identity_before_respawn(
            loop_id, project_dir, expected_repo_identity_hash, runtime, state=state
        ):
            del runtime.foreign_lease_cooldown_until[loop_id]
            continue
        del runtime.foreign_lease_cooldown_until[loop_id]
        runtime.workers[loop_id] = spawn_worker(loop_id, project_dir)
        respawned.append(loop_id)
        available -= 1
    return respawned


def _is_lease_expired(loop_id: str, project_dir: str) -> bool:
    """Return True when loop_id's lease is absent or past its TTL (no live owner holds it)."""
    lock = lc._read_lock(lc.lock_path(loop_id, project_dir))  # noqa: SLF001 - see _safe_stop_repo_identity_mismatch precedent
    return lock is None or not lc.is_lease_alive(lock)


def _untracked_live_active_loop_ids(runtime: SchedulerRuntime, project_dir: str) -> set[str]:
    """Return active (running/waiting_external) *and* still-pending loop_ids with a live lease
    this process has not tracked in `runtime.workers` (SN1, extended by #I2 for `pending`).

    This is exactly the set `respawn_orphaned_active_loops` correctly leaves alone (a live
    lease means some owner - typically a previous scheduler process's still-running child
    left behind by a scheduler restart - still holds it, so respawning would create a
    duplicate worker). `discover_loop_ids` already excludes all of `active_loop_ids()`
    (tracked or not) from fresh candidates, so these loop_ids can never be spawned as
    duplicates. But they still occupy a real, live concurrency slot even though
    `len(runtime.workers)` does not reflect it - without counting them here too,
    `spawn_new_workers`'s naive `concurrency_limit - len(runtime.workers)` availability
    calculation would undercount actual occupancy and spawn brand-new workers past the
    configured cap.

    #I2: a `pending` loop with a live lease (its worker's first `run_maker` is still in
    flight - typically left behind, like the active case above, by a previous scheduler
    process across a restart) is likewise untracked in a fresh `runtime.workers`, and
    `_pending_loop_ids` only keeps `discover_loop_ids` from re-spawning a duplicate for the
    *same* Issue (#G10) - it has no effect on the cap used when spawning workers for *other*
    Issues. Such a loop is never eligible for *automatic* respawn/attach here (`should_restart`
    rejects `pending` outright, and while `lc.attach()` itself can now recover a `pending`
    loop when called explicitly - Issue #205 - a live lease still makes any such attach raise
    `ForeignLeaseError` regardless), but it still holds a real, live slot until it finishes or
    its lease expires (at which point `recover_orphaned_pending_loops` retires it and frees
    the slot for real). A `pending` loop whose lease has already expired is left out here on
    purpose: it is orphan-recovery material (`recover_orphaned_pending_loops`, or a manual
    `attach`), not a live occupant of a slot.
    """
    live_active = {
        loop_id
        for loop_id in active_loop_ids(project_dir)
        if loop_id not in runtime.workers and not _is_lease_expired(loop_id, project_dir)
    }
    live_pending = {
        loop_id
        for loop_id in _pending_loop_ids(project_dir)
        if loop_id not in runtime.workers and not _is_lease_expired(loop_id, project_dir)
    }
    return live_active | live_pending


def _available_worker_slots(runtime: SchedulerRuntime, project_dir: str) -> int:
    """Return concurrency slots still free, counting tracked workers *and* untracked-live
    active/pending loops (SN1, extended by #I2 for `pending`).

    `respawn_orphaned_active_loops` and the cooldown-respawn path (`_respawn_expired_
    cooldowns`) previously computed availability from `concurrency_limit - len(runtime.
    workers)` alone - the exact same undercount `spawn_new_workers` used to have before
    `_untracked_live_active_loop_ids` was introduced for it (see that function's docstring).
    An untracked-but-live active loop (e.g. left running by a previous scheduler process
    across a restart) still occupies a real concurrency slot that neither of those two other
    respawn paths' naive calculation reflected, letting either spawn a worker past the
    configured cap whenever one was present. All three spawn/respawn paths now share this one
    occupancy calculation.
    """
    occupied = len(runtime.workers) + len(_untracked_live_active_loop_ids(runtime, project_dir))
    return concurrency_limit(project_dir) - occupied


def _recheck_repo_identity_before_respawn(
    loop_id: str,
    project_dir: str,
    expected_repo_identity_hash: str,
    runtime: SchedulerRuntime,
    state: lc.LoopState | None = None,
) -> bool:
    """Re-verify `loop_id`'s recorded repo-identity immediately before any respawn path
    (`respawn_orphaned_active_loops`, `_respawn_expired_cooldowns`, `reap_finished_workers`'s
    crash-restart branch) actually spawns a worker for it (J1).

    `verify_repo_identity_at_startup` only runs once, at scheduler startup. SN8 deliberately
    leaves a mismatched loop whose lease was still alive at that moment neither stopped nor
    tracked in `runtime.stopped_loop_ids` (see `_safe_stop_repo_identity_mismatch`'s own
    docstring) - the intent being it gets re-evaluated once the lease actually expires.
    But none of the three respawn paths re-ran the identity check on their own before this fix,
    so once that lease later expired mid-poll-loop, each would happily spawn a fresh
    `loop_driver.py` for a loop_id whose recorded repo-identity belongs to a different
    repository entirely. This reuses `_safe_stop_repo_identity_mismatch`'s own lease-aware
    stop/skip decision (and `_try_load_state`'s state (re)load, when the caller has not
    already loaded one) instead of duplicating either.

    Returns True when it is safe to respawn `loop_id` (repo identity matches, or the state
    could not be (re)loaded / already reached a terminal status - the caller's own subsequent
    handling covers that). Returns False when a mismatch was detected: the loop is either
    safety-stopped just now (lease already expired - `loop_id` is also added to
    `runtime.stopped_loop_ids` so later cycles stop reconsidering it) or left untouched for
    now (lease still alive - deferred to the next call, mirroring
    `verify_repo_identity_at_startup`'s own SN8 deferral).
    """
    if state is None:
        state = _try_load_state(lc.loop_dir(loop_id, project_dir), project_dir)
    if state is None or state.status in _NON_RESTARTABLE_STATUSES:
        return True
    if state.repo_identity_hash == expected_repo_identity_hash:
        return True
    if _safe_stop_repo_identity_mismatch(state, project_dir, expected_repo_identity_hash):
        runtime.stopped_loop_ids.add(loop_id)
    return False


def respawn_orphaned_active_loops(runtime: SchedulerRuntime, project_dir: str) -> list[str]:
    """Respawn active-status loops this process lost track of, e.g. after a restart (#F4).

    `discover_loop_ids` permanently excludes any loop_id in `active_loop_ids` (state.json
    status running/waiting_external) so discovery never regenerates an already-active loop.
    But `SchedulerRuntime.workers` is in-memory only: if the scheduler process itself
    restarts, `workers` starts empty, so a loop left running/waiting_external by the previous
    process becomes untracked *and* permanently invisible to discovery, with no path back to
    a worker actually being spawned for it. Only loops whose lease has actually expired are
    eligible here - a live lease means some owner (this process's own earlier-cycle child, or
    another host/process) still holds it, so respawning would create a duplicate worker.

    `stopped` (and `failed`) loops are never touched here because `active_loop_ids` only ever
    returns running/waiting_external, never a terminal status - so EV-51 (a safety-stopped
    loop is never auto-restarted) holds structurally, not via an extra check in this function.

    SN1: availability is computed via `_available_worker_slots` (tracked workers plus
    untracked-live active loops), not `concurrency_limit - len(runtime.workers)` alone - see
    that helper's docstring for why the naive count undercounts real occupancy.

    J1: `_recheck_repo_identity_before_respawn` re-verifies repo-identity immediately before
    respawning any loop_id here - see that helper's docstring for why the once-at-startup
    `verify_repo_identity_at_startup` check alone is insufficient for a loop whose lease was
    still alive at startup and only expires later, mid-poll-loop.
    """
    available = _available_worker_slots(runtime, project_dir)
    respawned: list[str] = []
    expected_repo_identity_hash: str | None = None
    for loop_id in active_loop_ids(project_dir):
        if available <= 0:
            break
        if loop_id in runtime.workers or loop_id in runtime.stopped_loop_ids:
            continue
        if loop_id in runtime.foreign_lease_cooldown_until:
            continue
        if not _is_lease_expired(loop_id, project_dir):
            continue
        if expected_repo_identity_hash is None:
            expected_repo_identity_hash = wm.resolve_repo_identity_hash(project_dir)
        if not _recheck_repo_identity_before_respawn(
            loop_id, project_dir, expected_repo_identity_hash, runtime
        ):
            continue
        runtime.workers[loop_id] = spawn_worker(loop_id, project_dir)
        respawned.append(loop_id)
        available -= 1
    return respawned


# Marker embedded in a retired `pending` loop's state-dir name (#H3/#H11). Real loop_ids are
# always `<repo-identity-hash>-issue-<N>` (see `worktree_manager.compute_loop_id`), which never
# contains this substring, so filtering on it cannot collide with a live loop_id. Defined in
# `loop_common.py` (as `ORPHANED_PENDING_MARKER`, SM1) so `loop_status.py` shares the same
# literal for purge-eligibility/display handling; aliased here under the historical private
# name to avoid rewriting every call site in this file.
_ORPHANED_PENDING_MARKER = lc.ORPHANED_PENDING_MARKER


def recover_orphaned_pending_loops(runtime: SchedulerRuntime, project_dir: str) -> list[str]:
    """Retire genuinely orphaned `pending` loops so their Issue can be discovered afresh
    (#H3/#H11).

    `should_restart("pending")` refuses to *automatically* respawn a `pending` loop (its
    worker never completed the first action, and an unconditional auto-respawn would restart-
    storm - see `should_restart`'s own docstring). `discover_loop_ids` also permanently
    excludes any still-`pending` loop_id from discovery (#G10) - so, taken together, a
    `pending` loop whose worker died (or whose owning scheduler process itself restarted) had
    no *automatic* path back at all: not respawned, not rediscovered, invisible forever even
    though its Issue still carries the label.

    This function does not respawn a worker or attach - a fresh worker cannot safely resume
    another worker's in-flight initial `run_maker` action, and this is deliberately an
    unattended, automatic recovery path rather than the explicit, journal-preserving `attach`
    recovery (Issue #205; `lc.attach()` can now recover a `pending` loop directly when a
    human/LP-1 caller invokes it, resuming the *same* `loop_id` and journal - see `attach`'s
    own docstring). Instead, once the loop's lease has genuinely expired (no live owner could
    still complete it), the state dir is renamed aside to `<loop_id>.orphaned-<n>` under
    `.claude/loop/` (automating the manual runbook step of moving the stale dir out of the
    way and letting a fresh `start` reuse the Issue, for the case no one attaches first) and
    the loop's worktree is best-effort cleaned up (#I7, see `_retire_orphaned_pending_dir`)
    so the next `start` for the same Issue does
    not silently resume from whatever uncommitted/partial edits the dead Maker left behind.
    Renaming (not deleting) the state dir preserves the abandoned run's journal/state for
    post-mortem, while `wm.compute_loop_id` for the same Issue number resolves to the same
    original `loop_id`, whose directory no longer exists, so the next discovery cycle treats
    it as a brand-new candidate.

    Loops still tracked in `runtime.workers` (this process's own in-flight worker, whose
    `state.json` simply has not yet reflected the first completed action) are left untouched,
    as is any loop whose lease is still alive (another owner might still complete it).

    SN-flock (PR #229 review, #205-race): the initial scan below is a cheap, unlocked
    pre-filter (mirrors `loop_status._purge_if_still_safe`'s candidate-list pattern) - the
    actual re-verification and rename happen inside `_retire_if_still_orphaned_pending`,
    under the same per-loop `held_coord_lock` `attach()` (via `reacquire_lease`) takes. Without
    that shared lock, a `pending` loop's `attach()` (Issue #205) could load a still-`pending`
    state here, then have this function rename its directory out from under it before
    `reacquire_lease`/`propose` run - surfacing as a spurious `lock_unavailable`/`invalid_state`
    for an attach that arrived just in time to legitimately recover the loop. Serializing both
    through the same coord lock, with a fresh lease-expiry re-check taken *inside* it
    immediately before the rename, closes that window: whichever of `attach()` or this
    retirement acquires the lock first "wins," and the loser's own fresh re-check (lease now
    alive because `attach()` reacquired it, or directory now gone) correctly no-ops.
    """
    root = lc.loop_root(project_dir)
    if not root.is_dir():
        return []
    recovered: list[str] = []
    for entry in sorted(root.iterdir()):
        if not entry.is_dir() or _ORPHANED_PENDING_MARKER in entry.name:
            continue
        loop_id = entry.name
        if loop_id in runtime.workers:
            continue
        state = _try_load_state(entry, project_dir)
        if state is None or state.status != "pending":
            continue
        if not _is_lease_expired(loop_id, project_dir):
            continue
        if _retire_if_still_orphaned_pending(loop_id, project_dir):
            recovered.append(loop_id)
    return recovered


def _retire_if_still_orphaned_pending(loop_id: str, project_dir: str) -> bool:
    """Re-verify `loop_id` is still an orphaned `pending` loop under the coord lock, then
    retire it (SN-flock, PR #229 review, #205-race - see `recover_orphaned_pending_loops`'s
    own docstring for the race this closes).

    Held under the same `lc.held_coord_lock` as `attach()` (via `reacquire_lease`), `resume`,
    and `purge`, so this cannot interleave with a concurrent `attach()` reclaiming the lease
    for the same `loop_id`. Both `state.status` and lease-expiry are reloaded fresh *inside*
    the lock - the caller's own pre-filter check is only a cheap, TOCTOU-prone hint, mirroring
    `loop_status._purge_if_still_safe`'s reload-immediately-before-mutating pattern. Returns
    False (no-op) when the loop no longer qualifies: status moved on, or `attach()` already
    reclaimed a live lease for it.
    """
    with lc.held_coord_lock(loop_id, project_dir):
        entry = lc.loop_dir(loop_id, project_dir)
        state = _try_load_state(entry, project_dir)
        if state is None or state.status != "pending":
            return False
        if not _is_lease_expired(loop_id, project_dir):
            return False
        _retire_orphaned_pending_dir(entry, project_dir)
        return True


def _retire_orphaned_pending_dir(entry: Path, project_dir: str) -> None:
    """Rename an orphaned-pending loop's state dir aside so discovery treats it as gone, and
    best-effort clean up its worktree (#I7).

    `worktree_manager.create_worktree` reuses an existing worktree directory on the expected
    branch as-is (never resets/cleans it) - without this cleanup, a dead Maker's uncommitted or
    partial edits would silently carry over into the fresh run this retirement is meant to
    enable, and could later be committed/pushed as if the new run authored them. Worktree
    removal is deliberately best-effort and never blocks retiring the state dir itself (that
    rename is what actually frees the Issue for rediscovery): a missing/already-removed
    worktree, or a `git worktree remove` failure, is only warned about.
    """
    root = entry.parent
    suffix = 1
    target = root / f"{entry.name}{_ORPHANED_PENDING_MARKER}{suffix}"
    while target.exists():
        suffix += 1
        target = root / f"{entry.name}{_ORPHANED_PENDING_MARKER}{suffix}"
    loop_id = entry.name
    entry.rename(target)
    print(
        lc.redact(f"loop_scheduler: recovered orphaned pending loop {loop_id} -> {target.name}"),
        file=sys.stderr,
    )
    _cleanup_orphaned_pending_worktree(loop_id, project_dir)


def _cleanup_orphaned_pending_worktree(loop_id: str, project_dir: str) -> None:
    """Best-effort removal of the worktree left behind by a retired orphaned-pending loop
    (#I7). Never raises: a cleanup failure must not block the state-dir retirement that already
    happened - it is only warned about here."""
    issue_number = lds.issue_number_from_loop_id(loop_id)
    if issue_number is None:
        return
    worktree_path = Path(wm.worktree_path_for(project_dir, issue_number))
    if not worktree_path.exists():
        return
    try:
        wm.remove_worktree(project_dir, issue_number, force=True)
    except wm.WorktreeError as exc:
        print(
            lc.redact(
                f"loop_scheduler: failed to clean up worktree for retired pending loop "
                f"{loop_id}: {exc}"
            ),
            file=sys.stderr,
        )


def reap_finished_workers(runtime: SchedulerRuntime, project_dir: str) -> list[str]:
    """Poll tracked workers; restart abnormal exits unless failed/stopped. Return respawned ids.

    SN6: dead workers are reaped (freeing their concurrency slots in `runtime.workers`) *before*
    `_respawn_expired_cooldowns` is checked, not after. Checking cooldowns first would compute
    `_respawn_expired_cooldowns`'s own concurrency-cap headroom against the still-stale
    `len(runtime.workers)` count - including workers that are about to be reaped by this very
    call - starving a cooldown-elapsed loop of a slot that is in fact freeing up in this same
    cycle, deferring its restart to (at least) the next poll interval instead.

    RH4: crash-restart candidates (the abnormal-exit, non-terminal, non-foreign-lease branch
    below) are collected into a list and spawned only *after* every finished worker has been
    popped from `runtime.workers` - not spawned immediately inline per finished worker as this
    used to do. Spawning immediately bypassed `_available_worker_slots` entirely: with cap=2,
    one dead worker + one live tracked worker + one untracked-but-live active loop (SN1) already
    fully occupies the cap, yet an inline immediate restart of the dead one would still spawn a
    third concurrent worker regardless. Restarts are now capped by the same shared
    `_available_worker_slots` occupancy calculation `_respawn_expired_cooldowns`,
    `respawn_orphaned_active_loops`, and `spawn_new_workers` already use; any candidate left over
    once slots run out is simply not restarted this cycle (its `state.json` status stays
    non-terminal, so it is picked up again - once its lease actually expires - by
    `respawn_orphaned_active_loops` on a later cycle instead of being lost).

    J1: `_recheck_repo_identity_before_respawn` re-verifies repo-identity immediately before
    restarting any crash-restart candidate below - see that helper's docstring for why the
    once-at-startup `verify_repo_identity_at_startup` check alone is insufficient here too.
    `restart_candidates` carries each candidate's already-loaded `state` along with its
    `loop_id` so the recheck does not need to reload state.json a second time.
    """
    finished = [loop_id for loop_id, proc in runtime.workers.items() if proc.poll() is not None]
    restart_candidates: list[tuple[str, lc.LoopState]] = []
    for loop_id in finished:
        proc = runtime.workers.pop(loop_id)
        if proc.returncode == 0 or loop_id in runtime.stopped_loop_ids:
            continue
        if proc.returncode == _EXIT_FOREIGN_LEASE:
            # The worker never reached `LoopDriver` (rejected at lease acquisition), so
            # `state.json.status` is still "running" (owned by whoever holds the live
            # lease). Respawning immediately every cycle would restart-storm until that
            # foreign lease's own TTL naturally expires; cool down instead.
            runtime.foreign_lease_cooldown_until[loop_id] = (
                time.monotonic() + lp2_lease_ttl_seconds(project_dir)
            )
            continue
        state = _try_load_state(lc.loop_dir(loop_id, project_dir), project_dir)
        if state is None or not should_restart(state.status):
            continue
        restart_candidates.append((loop_id, state))
    respawned: list[str] = []
    if restart_candidates:
        available = _available_worker_slots(runtime, project_dir)
        expected_repo_identity_hash: str | None = None
        for loop_id, state in restart_candidates:
            if available <= 0:
                break
            if expected_repo_identity_hash is None:
                expected_repo_identity_hash = wm.resolve_repo_identity_hash(project_dir)
            if not _recheck_repo_identity_before_respawn(
                loop_id, project_dir, expected_repo_identity_hash, runtime, state=state
            ):
                continue
            runtime.workers[loop_id] = spawn_worker(loop_id, project_dir)
            respawned.append(loop_id)
            available -= 1
    respawned.extend(_respawn_expired_cooldowns(runtime, project_dir))
    return respawned


def spawn_new_workers(
    runtime: SchedulerRuntime, project_dir: str, definition: ld.LoopDefinition
) -> list[str]:
    """Spawn newly discovered workers up to the concurrency cap (3.2 節).

    SN1: occupancy is computed via `_available_worker_slots`, which also counts
    `_untracked_live_active_loop_ids` - active loops with a live lease this process has not
    tracked in `runtime.workers` (e.g. left running by a previous scheduler process across a
    restart). `respawn_orphaned_active_loops` correctly does not touch them (their lease is
    still alive), so they never enter `runtime.workers`, but they are still real, live workers
    occupying a concurrency slot. Without counting them, `concurrency_limit -
    len(runtime.workers)` alone would undercount actual occupancy and spawn brand-new workers
    past the configured cap - the same undercount `_available_worker_slots` now also fixes for
    `respawn_orphaned_active_loops` and `_respawn_expired_cooldowns`.
    """
    available = _available_worker_slots(runtime, project_dir)
    if available <= 0:
        return []
    # #11: loop_ids mid-cooldown must also be excluded so discovery does not treat a
    # foreign-lease-rejected loop as a fresh candidate while it is waiting to be respawned.
    excluded = (
        runtime.stopped_loop_ids | set(runtime.workers) | set(runtime.foreign_lease_cooldown_until)
    )
    candidates = discover_loop_ids(project_dir, definition, excluded=excluded)
    spawned: list[str] = []
    for loop_id in candidates[:available]:
        runtime.workers[loop_id] = spawn_worker(loop_id, project_dir, definition.id)
        spawned.append(loop_id)
    return spawned


def run_cycle(runtime: SchedulerRuntime, project_dir: str, definition: ld.LoopDefinition) -> None:
    """One discovery -> cap check -> spawn / monitor / restart poll cycle.

    SN6: `reap_finished_workers` (which frees dead workers' slots, then respawns any
    cooldown-elapsed loop against the now-current slot count - see that function's docstring)
    runs first, ahead of `recover_orphaned_pending_loops` and `respawn_orphaned_active_loops`,
    so a slot a cooldown-elapsed loop is waiting on is never first handed to an unrelated
    recovered/orphaned-active loop instead.
    """
    reap_finished_workers(runtime, project_dir)
    # Must run before spawn_new_workers (#H3/#H11): retiring a stale `pending` state dir this
    # cycle lets discovery treat the same Issue as a fresh candidate in this same cycle,
    # instead of only on the next poll.
    recover_orphaned_pending_loops(runtime, project_dir)
    respawn_orphaned_active_loops(runtime, project_dir)
    spawn_new_workers(runtime, project_dir, definition)


# -- startup repo-identity verification (3.4 節: safety stop) ------------------------------------


def verify_repo_identity_at_startup(project_dir: str) -> list[str]:
    """Safety-stop any existing loop whose recorded repo-identity mismatches; return stopped ids.

    SN8: a mismatched loop whose lease is still alive is deliberately excluded from the
    returned list (see `_safe_stop_repo_identity_mismatch`) - it is neither stopped nor
    treated as already-handled, so it is re-evaluated on the next call (e.g. after the
    scheduler process restarts) once the lease has actually expired.
    """
    expected = wm.resolve_repo_identity_hash(project_dir)
    root = lc.loop_root(project_dir)
    if not root.is_dir():
        return []
    stopped: list[str] = []
    for entry in sorted(root.iterdir()):
        # A retired orphaned-pending dir (see `recover_orphaned_pending_loops`) still carries
        # the original `state.loop_id` inside its state.json, but its directory name has been
        # renamed aside with `_ORPHANED_PENDING_MARKER`. Without this filter,
        # `_safe_stop_repo_identity_mismatch(state, ...)` below would write a brand-new
        # `stopped` state.json at the *original* (no-suffix) loop_dir path - which no longer
        # exists - permanently orphaning both dirs: the original path becomes an unwanted
        # terminal state blocking Issue rediscovery, and the renamed dir is left untouched
        # (still `pending`, never cleaned up).
        if not entry.is_dir() or _ORPHANED_PENDING_MARKER in entry.name:
            continue
        state = _try_load_state(entry, project_dir)
        if state is None or state.status in _NON_RESTARTABLE_STATUSES:
            continue
        if state.repo_identity_hash == expected:
            continue
        if _safe_stop_repo_identity_mismatch(state, project_dir, expected):
            stopped.append(state.loop_id)
    return stopped


def _reload_for_safe_stop(
    state: lc.LoopState, project_dir: str, expected_repo_identity_hash: str
) -> lc.LoopState | None:
    """Re-load `state.loop_id`'s current state right after acquiring its coord lock (RH1).

    Return `None` whenever the stale, pre-lock `state` passed in must not be written through:
    the state dir vanished (purged), a purge tombstone now exists for it, its status already
    reached a terminal outcome, its `state_version` moved on (someone else wrote a newer state
    under this same coord lock in the meantime), or its repo-identity mismatch has since
    resolved itself. Otherwise return the freshly-reloaded state to write the stop onto.

    `verify_repo_identity_at_startup` necessarily reads `state` (the value passed in here)
    *before* acquiring this per-loop coord lock: the lock is keyed on `state.loop_id`, which is
    only known once state.json has already been read once. Between that read and the caller
    acquiring the lock, a concurrent `purge_loop` (RH3: tombstone-then-rmtree, both run under
    this very coord lock) can complete entirely - leaving a now-purged, tombstoned loop with no
    lock.json at all (`_is_lease_expired` returns True for a missing lock, so the existing
    lease-liveness check alone does not catch this). Writing the stale `state` through
    unconditionally at that point would resurrect a brand-new `stopped` state.json inside a
    directory `purge_loop`'s `rmtree` just deleted (`lc._write_state` recreates the parent dir
    via `_ensure_dir`), directly contradicting the tombstone that already marks this loop_id
    terminal/purged.
    """
    if state.loop_id in _tombstoned_loop_ids(project_dir):
        return None
    current = _try_load_state(lc.loop_dir(state.loop_id, project_dir), project_dir)
    if current is None:
        return None
    if current.status in _NON_RESTARTABLE_STATUSES:
        return None
    if current.state_version != state.state_version:
        return None
    if current.repo_identity_hash == expected_repo_identity_hash:
        return None
    return current


def _safe_stop_repo_identity_mismatch(
    state: lc.LoopState, project_dir: str, expected_repo_identity_hash: str
) -> bool:
    """Journal-first -> state -> mandatory macOS notify -> no Issue comment (3.4 節).
    Return True iff the stop was actually written.

    Written directly (not via `loop_driver_support.persist_safe_stop`) because the
    scheduler holds no lease for a loop it is refusing to touch precisely because the
    repository identity looks wrong; a foreign/stale lease token is not evidence this
    write is unsafe the way it is for the driver's own in-flight writes.

    SN8: this function does not itself fence its `state.json` write against a live
    lease (see above - it deliberately holds none). If `state.loop_id`'s lease is still
    alive, a detached worker legitimately owns it and would overwrite this unfenced
    `stopped` write with its own next in-flight persist moments later, silently
    reverting the safety-stop. Guard against that by skipping the write entirely while
    the lease is alive (logging a warning instead) - the loop is left untouched and
    excluded from the returned `stopped` set, so it is retried (not permanently
    swallowed) the next time `verify_repo_identity_at_startup` runs, by which point the
    worker will have exited or its lease will have expired and this write can no longer
    race a live owner.

    SN-flock: the lease check + write is additionally held under `lc.held_coord_lock` (a
    fixed, purge-independent path shared with `loop_status._purge_if_still_safe` and
    `loop_common.resume`/`reacquire_lease`, see their docstrings), so this write cannot race a
    concurrent purge of the same `loop_id` either (not just a live worker's own lease as
    covered above).

    RH1: `state` (the caller's pre-coord-lock read) is re-validated via `_reload_for_safe_stop`
    immediately after the lease-liveness check above, once this call actually holds the coord
    lock - see that helper's docstring for the stale-read race this closes. The rest of this
    function writes the freshly-reloaded state (not the stale `state` argument).
    """
    with lc.held_coord_lock(state.loop_id, project_dir):
        if not _is_lease_expired(state.loop_id, project_dir):
            print(
                lc.redact(
                    f"loop_scheduler: {state.loop_id} repo_identity_mismatch detected but its "
                    "lease is still held by a live worker; deferring safety-stop until the "
                    "lease expires"
                ),
                file=sys.stderr,
            )
            return False
        current = _reload_for_safe_stop(state, project_dir, expected_repo_identity_hash)
        if current is None:
            print(
                lc.redact(
                    f"loop_scheduler: {state.loop_id} repo_identity_mismatch stop skipped - its "
                    "state was purged, changed, or already resolved while waiting for the "
                    "coord lock"
                ),
                file=sys.stderr,
            )
            return False
        state = current
        lc.append_journal_event(
            state.loop_id,
            project_dir,
            "stopped",
            "scheduler",
            None,
            {"stop_reason": "repo_identity_mismatch"},
        )
        state.status = "stopped"
        state.stop_reason = "repo_identity_mismatch"
        state.pending_action = None
        state.state_version += 1
        state.updated_at = lc.now_iso()
        lc._write_state(state, project_dir)  # noqa: SLF001 - package-internal writer, see docstring
    lc.emit_loop_audit_event(
        "loop_stop",
        project_dir,
        {
            "loop_id": state.loop_id,
            "phase": state.phase,
            "final_status": "stopped",
            "stop_reason": "repo_identity_mismatch",
            "pr_number": state.pr_number,
        },
    )
    lds.notify_macos("loop-harness", lc.redact(f"{state.loop_id}: repo_identity_mismatch"))
    print(
        lc.redact(f"loop_scheduler: {state.loop_id} stopped (repo_identity_mismatch)"),
        file=sys.stderr,
    )
    return True


# -- main poll loop --------------------------------------------------------------------------


def run_scheduler(
    project_dir: str,
    definition_id: str = DEFAULT_DEFINITION_ID,
    *,
    max_cycles: int | None = None,
) -> None:
    """Run the resident scheduler loop (forever unless max_cycles is given for tests)."""
    definition = ld.load_all_definitions(project_dir).get(definition_id)
    if definition is None:
        raise ld.DefinitionValidationError(f"loop definition not found: {definition_id}")
    runtime = SchedulerRuntime()
    runtime.stopped_loop_ids.update(verify_repo_identity_at_startup(project_dir))
    poll_interval = resolve_poll_interval(definition)
    cycles = 0
    while max_cycles is None or cycles < max_cycles:
        try:
            run_cycle(runtime, project_dir, definition)
        except Exception as exc:  # noqa: BLE001 - a resident poller must survive a bad cycle (#21)
            print(lc.redact(f"loop_scheduler: poll cycle failed: {exc}"), file=sys.stderr)
        cycles += 1
        if max_cycles is not None and cycles >= max_cycles:
            break
        time.sleep(poll_interval)


