from __future__ import annotations

import json
from pathlib import Path


def _setup_context_packages(orchestra_dir: Path, extra_packages: dict | None = None) -> None:
    """context_files を含む minimal manifest を作成する。"""
    packages = {
        "core": {
            "name": "core",
            "version": "0.0.0",
            "depends": [],
            "context_files": {
                "source": "claude.md",
                "template": "templates/project/CLAUDE.md",
                "init": ["CLAUDE.md"],
                "sync": ["CLAUDE.md"],
            },
        },
        "codex-suggestions": {
            "name": "codex-suggestions",
            "version": "0.0.0",
            "depends": [],
            "context_files": {
                "source": "codex.md",
                "fragments": ["antigravity.md"],
                "template": "templates/codex/AGENTS.md",
                "init": ["AGENTS.md"],
                "sync": ["AGENTS.md"],
            },
        },
    }
    if extra_packages:
        packages.update(extra_packages)
    packages_dir = orchestra_dir / "packages"
    packages_dir.mkdir(parents=True, exist_ok=True)
    for pkg_name, manifest in packages.items():
        pkg_dir = packages_dir / pkg_name
        pkg_dir.mkdir(parents=True, exist_ok=True)
        (pkg_dir / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")


import pytest

