class TestLegacyContextCleanup:
    """配布廃止済み context ファイル（.gemini/GEMINI.md）の安全クリーンアップ。"""

    GENERATED_GEMINI = (
        "<!-- DO NOT EDIT: generated by `orchex context build` -->\n\n# GEMINI\n\nold body\n"
    )

    def _make_project(self, tmp_path: Path) -> tuple[OrchestraManager, Path]:
        orchestra_dir = tmp_path / "orchestra"
        project_dir = tmp_path / "project"
        project_dir.mkdir(parents=True)
        _setup_context_sources(orchestra_dir)
        _setup_orchestra_json(project_dir)
        return OrchestraManager(orchestra_dir), project_dir

    def test_generated_gemini_md_is_removed(self, tmp_path: Path) -> None:
        manager, project_dir = self._make_project(tmp_path)
        legacy = project_dir / ".gemini" / "GEMINI.md"
        legacy.parent.mkdir(parents=True)
        legacy.write_text(self.GENERATED_GEMINI, encoding="utf-8")

        manager.context_sync(str(project_dir))

        assert not legacy.exists()

    def test_handwritten_gemini_md_is_kept(self, tmp_path: Path) -> None:
        """生成物マーカーのないファイル（ユーザー手書き）は削除しない。"""
        manager, project_dir = self._make_project(tmp_path)
        legacy = project_dir / ".gemini" / "GEMINI.md"
        legacy.parent.mkdir(parents=True)
        legacy.write_text("# My custom Gemini instructions\n", encoding="utf-8")

        manager.context_sync(str(project_dir))

        assert legacy.exists()
        assert "My custom" in legacy.read_text(encoding="utf-8")

    def test_dry_run_does_not_remove(self, tmp_path: Path) -> None:
        manager, project_dir = self._make_project(tmp_path)
        legacy = project_dir / ".gemini" / "GEMINI.md"
        legacy.parent.mkdir(parents=True)
        legacy.write_text(self.GENERATED_GEMINI, encoding="utf-8")

        manager.context_sync(str(project_dir), dry_run=True)

        assert legacy.exists()

    def test_no_gemini_md_is_noop(self, tmp_path: Path) -> None:
        manager, project_dir = self._make_project(tmp_path)

        changed = manager.context_sync(str(project_dir))

        assert changed == 2


